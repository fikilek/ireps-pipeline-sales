def discover_monthly_files(monthly_dir: Path, months: Iterable[str]) -> dict[str, Path]:
    expected_months = list(months)
    discovered: dict[str, Path] = {}

    for path in monthly_dir.iterdir():
        if not path.is_file():
            continue
        match = MONTHLY_FILENAME_RE.fullmatch(path.name)
        if not match:
            continue
        ym = match.group(1)
        if ym not in expected_months:
            continue
        if ym in discovered:
            raise ValueError(
                f"Multiple monthly files found for {ym}: {discovered[ym]} and {path}"
            )
        discovered[ym] = path.resolve()

    missing = [ym for ym in expected_months if ym not in discovered]
    if missing:
        raise FileNotFoundError(
            "Required monthly meter-level files are missing for: " + ", ".join(missing)
        )

    return {ym: discovered[ym] for ym in expected_months}


def validate_output_identity(
    path: Path,
    lm_pcode: str,
    from_month: str,
    to_month: str,
) -> None:
    expected_name = (
        f"sales_all_meters__{lm_pcode}__FULL__{from_month}_to_{to_month}.csv"
    )
    if path.parent.resolve() != GOVERNED_OUTPUT_DIR:
        raise ValueError(
            "Stage 06 output must be written to the governed output directory: "
            f"expected {GOVERNED_OUTPUT_DIR}, found {path.parent.resolve()}"
        )
    if path.name != expected_name:
        raise ValueError(
            "Stage 06 output filename must match the governed identity exactly: "
            f"expected {expected_name!r}, found {path.name!r}"
        )


def load_master(
    config: BuildConfig,
    stats: BuildStats,
    snapshot: CsvSnapshot,
) -> dict[str, dict[str, Any]]:
    df = snapshot.frame.copy()
    actual_columns = list(df.columns)
    if actual_columns != MASTER_COLUMNS:
        raise ValueError(
            "Meter Master columns do not match the approved ten-column contract. "
            f"Expected={MASTER_COLUMNS}; actual={actual_columns}"
        )
    if df.empty:
        raise ValueError("Meter Master CSV contains zero rows.")

    records: dict[str, dict[str, Any]] = {}
    for row_number, row in enumerate(df.to_dict("records"), start=2):
        master_raw = safe_str(row.get("masterId"))
        normalized_raw = safe_str(row.get("meterNoNormalized"))
        sales_raw = safe_str(row.get("salesId"))
        master_id = normalize_meter_no(master_raw)
        normalized = normalize_meter_no(normalized_raw)
        raw = safe_str(row.get("meterNoRaw"))
        lm_pcode = safe_str(row.get("lmPcode"))
        sales_id = normalize_meter_no(sales_raw)
        provider = safe_str(row.get("salesProvider"))
        meter_type = safe_str(row.get("meterType"))

        validate_meter_no(master_id, "masterId", row_number)
        validate_meter_no(normalized, "meterNoNormalized", row_number)
        validate_meter_no(sales_id, "salesId", row_number)
        for label, original, canonical in (
            ("masterId", master_raw, master_id),
            ("meterNoNormalized", normalized_raw, normalized),
            ("salesId", sales_raw, sales_id),
        ):
            if original != canonical:
                raise ValueError(
                    f"{label} must already be canonical uppercase alphanumeric text at "
                    f"row {row_number}: {original!r} -> {canonical!r}"
                )
        if master_id != normalized:
            raise ValueError(
                f"masterId must equal meterNoNormalized at row {row_number}: "
                f"{master_id!r} != {normalized!r}"
            )
        if sales_id != normalized:
            raise ValueError(
                f"salesId must equal meterNoNormalized at row {row_number}: "
                f"{sales_id!r} != {normalized!r}"
            )
        if lm_pcode != config.lm_pcode:
            raise ValueError(
                f"Meter Master LM mismatch at row {row_number}: "
                f"expected {config.lm_pcode!r}, found {lm_pcode!r}"
            )
        if provider != GOVERNED_PROVIDER:
            raise ValueError(
                f"salesProvider must be {GOVERNED_PROVIDER!r} at row {row_number}; found {provider!r}"
            )
        if meter_type != GOVERNED_METER_TYPE:
            raise ValueError(
                f"meterType must be {GOVERNED_METER_TYPE!r} at row {row_number}; found {meter_type!r}"
            )
        if master_id in records:
            raise ValueError(f"Duplicate masterId in Meter Master: {master_id!r}")

        records[master_id] = {
            "masterId": master_id,
            "meterNo": raw,
            "meterNoNormalized": normalized,
            "provider": provider,
            "customerNo": safe_str(row.get("customerNo")),
            "accountNo": safe_str(row.get("accountNo")),
            "months": {},
            "totalAmountC": 0,
            "lastPurchase": None,
        }

    stats.master_rows = len(records)
    return records


def validate_monthly_purchase(
    *,
    amount: int,
    purchase: datetime | None,
    ym: str,
    approved_months: set[str],
    path: Path,
    row_number: int,
) -> None:
    if ym not in approved_months:
        raise ValueError(
            f"{path} contains month {ym!r} outside the approved Stage 06 range."
        )
    if amount > 0 and purchase is None:
        raise ValueError(
            f"{path} has positive amountTotalC but blank lastPurchaseAtISO "
            f"at row {row_number}."
        )
    if purchase is not None:
        purchase_month = purchase.strftime("%Y-%m")
        if purchase_month != ym:
            raise ValueError(
                f"{path} lastPurchaseAtISO belongs to {purchase_month!r} at row "
                f"{row_number}; expected the applicable sales month {ym!r}."
            )


def load_monthly_files(
    config: BuildConfig,
    monthly_snapshots: Mapping[str, CsvSnapshot],
    records: dict[str, dict[str, Any]],
    stats: BuildStats,
) -> None:
    unknown_meters: list[tuple[str, str, int]] = []

    approved_months = set(month_range(config.from_month, config.to_month))
    for ym, snapshot in monthly_snapshots.items():
        path = snapshot.path
        df = snapshot.frame.copy()
        missing_columns = [column for column in MONTHLY_REQUIRED_COLUMNS if column not in df.columns]
        if missing_columns:
            raise ValueError(f"{path} is missing required columns: {missing_columns}")

        seen_meters: set[str] = set()
        for row_number, row in enumerate(df.to_dict("records"), start=2):
            row_lm = safe_str(row.get("lmPcode"))
            row_ym = safe_str(row.get("ym"))
            meter = normalize_meter_no(row.get("meterNo"))

            if row_lm != config.lm_pcode:
                raise ValueError(
                    f"{path} contains LM {row_lm!r} at row {row_number}; "
                    f"expected only {config.lm_pcode!r}."
                )
            if row_ym != ym:
                raise ValueError(
                    f"{path} contains ym={row_ym!r} at row {row_number}; expected {ym!r}."
                )
            validate_meter_no(meter, "meterNo", row_number)
            if meter in seen_meters:
                raise ValueError(f"{path} contains duplicate meter {meter!r} for month {ym}.")
            seen_meters.add(meter)

            record = records.get(meter)
            if record is None:
                if len(unknown_meters) < 20:
                    unknown_meters.append((ym, meter, row_number))
                continue

            amount = parse_nonnegative_int(row.get("amountTotalC"), "amountTotalC", row_number)
            purchase = parse_iso(row.get("lastPurchaseAtISO"), "lastPurchaseAtISO", row_number)
            validate_monthly_purchase(
                amount=amount,
                purchase=purchase,
                ym=ym,
                approved_months=approved_months,
                path=path,
                row_number=row_number,
            )

            record["months"][ym] = amount
            record["totalAmountC"] += amount
            if amount > 0 and purchase is not None and (
                record["lastPurchase"] is None or purchase > record["lastPurchase"]
            ):
                record["lastPurchase"] = purchase
            stats.monthly_rows += 1

    if unknown_meters:
        examples = ", ".join(
            f"{ym}:{meter} (row {row_number})"
            for ym, meter, row_number in unknown_meters[:10]
        )
        raise ValueError(
            "Monthly sales contain meter(s) absent from the approved Meter Master. "
            f"Examples: {examples}"
        )


def finalize_rows(
    config: BuildConfig,
    months: list[str],
    records: dict[str, dict[str, Any]],
    stats: BuildStats,
) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for record in records.values():
        last_purchase: datetime | None = record["lastPurchase"]
        if record["totalAmountC"] == 0:
            last_purchase = None
        if record["totalAmountC"] > 0 and last_purchase is None:
            raise ValueError(
                f"Meter {record['masterId']} has positive totalAmountC but no valid "
                "lastPurchaseAtISO in the approved monthly range."
            )
        if last_purchase is None:
            last_purchase_iso = ""
            days_since: int | str = ""
        else:
            last_purchase_iso = last_purchase.isoformat().replace("+00:00", "Z")
            days_since_value = (config.as_of_date - last_purchase.date()).days
            if days_since_value < 0:
                raise ValueError(
                    f"Last purchase for {record['masterId']} occurs after --as-of-date: "
                    f"{last_purchase_iso} > {config.as_of_date.isoformat()}"
                )
            days_since = days_since_value

        row: dict[str, Any] = {
            "masterId": record["masterId"],
            "meterNo": record["meterNo"],
            "meterNoNormalized": record["meterNoNormalized"],
            "provider": record["provider"],
            "customerNo": record["customerNo"],
            "accountNo": record["accountNo"],
            "totalAmountC": record["totalAmountC"],
            "lastPurchaseAtISO": last_purchase_iso,
            "daysSinceLastPurchase": days_since,
        }
        for ym in months:
            row[f"amount_{ym.replace('-', '_')}_C"] = record["months"].get(ym, 0)
        rows.append(row)

        if record["totalAmountC"] > 0:
            stats.meters_with_sales += 1
        else:
            stats.meters_without_sales += 1
    monthly_columns = [f"amount_{ym.replace('-', '_')}_C" for ym in months]
    output_columns = BASE_OUTPUT_COLUMNS + monthly_columns
    df = pd.DataFrame(rows, columns=output_columns)
    return df.sort_values(
        by=["meterNoNormalized", "meterNo"],
        ascending=[True, True],
        kind="stable",
    ).reset_index(drop=True)


def validate_output(df: pd.DataFrame, months: list[str], expected_rows: int) -> None:
    if len(df) != expected_rows:
        raise ValueError(f"Output row count mismatch: expected {expected_rows}, found {len(df)}")
    if df.empty:
        raise ValueError("Sales All Meters output contains zero rows.")
    if df["masterId"].eq("").any():
        raise ValueError("Sales All Meters output contains blank masterId values.")
    if df["masterId"].duplicated().any():
        examples = df.loc[df["masterId"].duplicated(keep=False), "masterId"].head(10).tolist()
        raise ValueError(f"Sales All Meters output contains duplicate masterId values: {examples}")
    if not (df["masterId"] == df["meterNoNormalized"]).all():
        raise ValueError("Sales All Meters output contains masterId/meterNoNormalized mismatches.")
    if "visibility" in df.columns:
        raise ValueError(
            "Sales All Meters staging must not contain visibility; "
            "operational registration/discovery/installation writers own master.visibility."
        )

    positive = df["totalAmountC"].astype("int64") > 0
    if df.loc[positive, "lastPurchaseAtISO"].astype(str).str.strip().eq("").any():
        raise ValueError(
            "Sales All Meters output has positive totalAmountC with blank lastPurchaseAtISO."
        )
    if df.loc[positive, "daysSinceLastPurchase"].astype(str).str.strip().eq("").any():
        raise ValueError(
            "Sales All Meters output has positive totalAmountC with blank daysSinceLastPurchase."
        )
    no_sales = ~positive
    if df.loc[no_sales, "lastPurchaseAtISO"].astype(str).str.strip().ne("").any():
        raise ValueError(
            "Sales All Meters output has zero totalAmountC with populated lastPurchaseAtISO."
        )
    if df.loc[no_sales, "daysSinceLastPurchase"].astype(str).str.strip().ne("").any():
        raise ValueError(
            "Sales All Meters output has zero totalAmountC with populated daysSinceLastPurchase."
        )

    monthly_columns = [f"amount_{ym.replace('-', '_')}_C" for ym in months]
    calculated_totals = df[monthly_columns].astype("int64").sum(axis=1)
    reported_totals = df["totalAmountC"].astype("int64")
    mismatches = calculated_totals != reported_totals
    if mismatches.any():
        sample = df.loc[mismatches, ["masterId", "totalAmountC"] + monthly_columns].head(10)
        raise ValueError(
            "totalAmountC does not reconcile to the included monthly columns. Examples:\n"
            + sample.to_string(index=False)
        )


def build_config(args: argparse.Namespace) -> BuildConfig:
    lm_pcode = safe_str(args.lm_pcode).upper()
    if not lm_pcode:
        raise ValueError("--lm-pcode may not be blank.")
    months = month_range(args.from_month, args.to_month)
    if not months:
        raise ValueError("The requested month range is empty.")

    output_path = resolve_project_path(args.output).resolve()
    config = BuildConfig(
        lm_pcode=lm_pcode,
        from_month=months[0],
        to_month=months[-1],
        master_path=resolve_project_path(args.master).resolve(),
        master_manifest_path=resolve_project_path(args.master_manifest).resolve(),
        monthly_dir=resolve_project_path(args.monthly_dir).resolve(),
        output_path=output_path,
        manifest_path=output_path.with_suffix(".manifest.json"),
        as_of_date=parse_as_of_date(args.as_of_date),
    )
    validate_output_identity(
        config.output_path,
        config.lm_pcode,
        config.from_month,
        config.to_month,
    )
    return config


