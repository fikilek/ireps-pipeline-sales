def resolve_project_path(path: Path) -> Path:
    return path if path.is_absolute() else PROJECT_ROOT / path


def safe_str(value: Any) -> str:
    if value is None or pd.isna(value):
        return ""
    text = str(value).strip()
    return "" if text.lower() == "nan" else text


def normalize_meter_no(value: Any) -> str:
    return re.sub(r"\s+", "", safe_str(value)).upper()


def validate_meter_no(value: str, label: str, row_number: int) -> None:
    if not value:
        raise ValueError(f"{label} is blank at row {row_number}.")
    if not METER_RE.fullmatch(value):
        raise ValueError(
            f"{label} contains invalid characters at row {row_number}: {value!r}"
        )


def parse_month(value: str, label: str) -> tuple[int, int]:
    match = MONTH_RE.fullmatch(safe_str(value))
    if not match:
        raise ValueError(f"{label} must use YYYY-MM format: {value!r}")
    year, month = int(match.group(1)), int(match.group(2))
    if not 1 <= month <= 12:
        raise ValueError(f"{label} has an invalid month: {value!r}")
    return year, month


def month_range(from_month: str, to_month: str) -> list[str]:
    start_year, start_month = parse_month(from_month, "--from-month")
    end_year, end_month = parse_month(to_month, "--to-month")
    if (start_year, start_month) > (end_year, end_month):
        raise ValueError("--from-month may not be later than --to-month.")

    result: list[str] = []
    year, month = start_year, start_month
    while (year, month) <= (end_year, end_month):
        result.append(f"{year:04d}-{month:02d}")
        month += 1
        if month == 13:
            month = 1
            year += 1
    return result


def parse_iso(value: Any, label: str, row_number: int) -> datetime | None:
    text = safe_str(value)
    if not text:
        return None
    try:
        parsed = datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError(
            f"{label} is not a valid ISO timestamp at row {row_number}: {text!r}"
        ) from exc
    if parsed.tzinfo is None:
        raise ValueError(
            f"{label} must include a timezone at row {row_number}: {text!r}"
        )
    return parsed.astimezone(UTC)


def parse_nonnegative_int(value: Any, label: str, row_number: int) -> int:
    text = safe_str(value)
    if not text:
        raise ValueError(f"{label} is blank at row {row_number}.")
    try:
        number = Decimal(text)
    except InvalidOperation as exc:
        raise ValueError(f"{label} is not numeric at row {row_number}: {text!r}") from exc
    if number != number.to_integral_value():
        raise ValueError(f"{label} is not a whole number at row {row_number}: {text!r}")
    integer = int(number)
    if integer < 0:
        raise ValueError(f"{label} may not be negative at row {row_number}: {integer}")
    return integer


def parse_as_of_date(value: str) -> date:
    try:
        return date.fromisoformat(value)
    except ValueError as exc:
        raise ValueError(f"--as-of-date must use YYYY-MM-DD format: {value!r}") from exc


def require_file(path: Path, label: str) -> None:
    if not path.is_file():
        raise FileNotFoundError(f"{label} not found: {path}")


def require_directory(path: Path, label: str) -> None:
    if not path.is_dir():
        raise FileNotFoundError(f"{label} not found: {path}")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def canonical_json_sha256(payload: Any) -> str:
    encoded = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def document_ids_sha256(values: Sequence[str]) -> str:
    return canonical_json_sha256(sorted(values))


def read_json_snapshot(path: Path, label: str) -> JsonSnapshot:
    require_file(path, label)
    raw = path.read_bytes()
    try:
        payload = json.loads(raw.decode("utf-8-sig"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"{label} is not valid JSON: {path}") from exc
    if not isinstance(payload, dict):
        raise ValueError(f"{label} must contain one JSON object: {path}")
    return JsonSnapshot(path=path, payload=payload, sha256=sha256_bytes(raw))


def read_csv_snapshot(path: Path, label: str) -> CsvSnapshot:
    require_file(path, label)
    raw = path.read_bytes()
    try:
        frame = pd.read_csv(io.BytesIO(raw), dtype=str, encoding="utf-8-sig").fillna("")
    except Exception as exc:
        raise ValueError(f"{label} is not a valid CSV: {path}") from exc
    return CsvSnapshot(path=path, frame=frame, sha256=sha256_bytes(raw))


def stage05_fingerprint_contract(manifest: Mapping[str, Any]) -> dict[str, Any]:
    source = manifest.get("sourceContract")
    output = manifest.get("outputContract")
    stats = manifest.get("stats")
    if not isinstance(source, Mapping) or not isinstance(output, Mapping) or not isinstance(stats, Mapping):
        raise ValueError("Stage 05 manifest is missing sourceContract, outputContract, or stats")
    monthly = source.get("monthlyInputs")
    if not isinstance(monthly, list):
        raise ValueError("Stage 05 manifest sourceContract.monthlyInputs must be a list")
    monthly_contract: list[dict[str, Any]] = []
    for item in monthly:
        if not isinstance(item, Mapping):
            continue
        stage03 = item.get("stage03Manifest")
        if not isinstance(stage03, Mapping):
            stage03 = {}
        atomic = stage03.get("atomicFile")
        if not isinstance(atomic, Mapping):
            atomic = {}
        reconciliation = stage03.get("reconciliation")
        if not isinstance(reconciliation, Mapping):
            reconciliation = {}
        monthly_contract.append(
            {
                "month": item.get("month"),
                "filename": item.get("filename"),
                "rows": item.get("rows"),
                "columns": item.get("columns"),
                "sha256": item.get("sha256"),
                "stage03Manifest": {
                    "filename": stage03.get("filename"),
                    "sha256": stage03.get("sha256"),
                    "atomicFile": {
                        "filename": atomic.get("filename"),
                        "rows": atomic.get("rows"),
                        "sha256": atomic.get("sha256"),
                    },
                    "reconciliation": dict(reconciliation),
                },
            }
        )
    return {
        "lmPcode": source.get("lmPcode"),
        "scope": source.get("scope"),
        "fromMonth": source.get("fromMonth"),
        "toMonth": source.get("toMonth"),
        "includedMonths": source.get("includedMonths"),
        "provider": source.get("provider"),
        "meterType": source.get("meterType"),
        "monthlyInputs": monthly_contract,
        "customerDetails": {
            "filename": (source.get("customerDetails") or {}).get("filename"),
            "rows": (source.get("customerDetails") or {}).get("rows"),
            "sha256": (source.get("customerDetails") or {}).get("sha256"),
        },
        "npr": {
            "filename": (source.get("npr") or {}).get("filename"),
            "rows": (source.get("npr") or {}).get("rows"),
            "sha256": (source.get("npr") or {}).get("sha256"),
        },
        "output": {
            "filename": output.get("filename"),
            "rows": output.get("rows"),
            "columns": output.get("columns"),
            "sha256": output.get("sha256"),
        },
        "stats": dict(stats),
    }


def validate_stage05_manifest(
    config: BuildConfig,
    months: Sequence[str],
    manifest_snapshot: JsonSnapshot,
    master_snapshot: CsvSnapshot,
    monthly_snapshots: Mapping[str, CsvSnapshot],
) -> dict[str, Any]:
    manifest = manifest_snapshot.payload
    if manifest.get("schemaVersion") != 1:
        raise ValueError("Unsupported Stage 05 manifest schemaVersion")
    if manifest.get("stage") != "05" or manifest.get("script") != "05_build_meter_master_v3.py":
        raise ValueError("Manifest is not from Stage 05")
    if manifest.get("status") != "PASS" or manifest.get("result") != "BUILD_WRITTEN":
        raise ValueError("Stage 05 manifest is not a successful frozen build")
    recorded = safe_str(manifest.get("buildFingerprint"))
    calculated = canonical_json_sha256(stage05_fingerprint_contract(manifest))
    if recorded != calculated:
        raise ValueError("Stage 05 buildFingerprint is invalid; manifest may be edited or corrupt")

    source = manifest["sourceContract"]
    output = manifest["outputContract"]
    if source.get("lmPcode") != config.lm_pcode:
        raise ValueError("Stage 05 manifest LM does not match Stage 06")
    if source.get("fromMonth") != config.from_month or source.get("toMonth") != config.to_month:
        raise ValueError("Stage 05 manifest range does not match Stage 06")
    if source.get("includedMonths") != list(months):
        raise ValueError("Stage 05 includedMonths do not match Stage 06")
    if source.get("provider") != GOVERNED_PROVIDER or source.get("meterType") != GOVERNED_METER_TYPE:
        raise ValueError("Stage 05 manifest provider or meter type is outside the governed contract")
    if output.get("filename") != config.master_path.name:
        raise ValueError("Stage 05 manifest output filename does not match --master")
    if output.get("columns") != MASTER_COLUMNS:
        raise ValueError("Stage 05 manifest Meter Master columns do not match the approved contract")
    actual_master_sha = master_snapshot.sha256
    if output.get("sha256") != actual_master_sha:
        raise ValueError("Meter Master CSV SHA-256 does not match the Stage 05 manifest")
    actual_master_rows = len(master_snapshot.frame)
    if output.get("rows") != actual_master_rows:
        raise ValueError("Meter Master CSV row count does not match the Stage 05 manifest")

    evidence = source.get("monthlyInputs")
    if not isinstance(evidence, list) or len(evidence) != len(months):
        raise ValueError("Stage 05 manifest monthly input evidence is incomplete")
    by_month = {safe_str(item.get("month")): item for item in evidence if isinstance(item, Mapping)}
    if sorted(by_month) != sorted(months):
        raise ValueError("Stage 05 manifest monthly input month set does not match Stage 06")
    validated_monthly: list[dict[str, Any]] = []
    for month in months:
        item = by_month[month]
        snapshot = monthly_snapshots[month]
        path = snapshot.path
        actual = {
            "month": month,
            "path": str(path),
            "filename": path.name,
            "rows": len(snapshot.frame),
            "columns": list(snapshot.frame.columns),
            "sha256": snapshot.sha256,
        }
        if actual["columns"] != MONTHLY_COLUMNS:
            raise ValueError(
                f"Monthly input {month} columns do not match the approved Stage 03 schema"
            )
        for field in ("filename", "rows", "columns", "sha256"):
            if item.get(field) != actual[field]:
                raise ValueError(
                    f"Monthly input {month} {field} does not match the approved Stage 05 evidence"
                )
        validated_monthly.append(actual)

    return {
        "manifestPath": str(manifest_snapshot.path),
        "manifestFilename": manifest_snapshot.path.name,
        "manifestSha256": manifest_snapshot.sha256,
        "buildFingerprint": recorded,
        "master": {
            "path": str(config.master_path),
            "filename": config.master_path.name,
            "rows": actual_master_rows,
            "columns": MASTER_COLUMNS,
            "sha256": actual_master_sha,
        },
        "monthlyInputs": validated_monthly,
    }


def utc_iso_now() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def write_csv_atomic(df: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    try:
        df.to_csv(temporary, index=False, encoding="utf-8")
        temporary.replace(path)
    finally:
        if temporary.exists():
            temporary.unlink()


def write_json_atomic(payload: Mapping[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="\n") as target:
            json.dump(payload, target, indent=2, sort_keys=True, ensure_ascii=False)
            target.write("\n")
        temporary.replace(path)
    finally:
        if temporary.exists():
            temporary.unlink()


